package conda

import (
	"sort"

	"go.yaml.in/yaml/v3"
)

func mirrorMapping(root *yaml.Node, name string) *yaml.Node {
	for i := 0; i < len(root.Content); i += 2 {
		if root.Content[i].Value == name {
			return root.Content[i+1]
		}
	}
	return nil
}

func setMirrorMapping(root *yaml.Node, name string, value *yaml.Node, final bool) {
	for i := 0; i < len(root.Content); i += 2 {
		if root.Content[i].Value == name {
			root.Content[i+1] = value
			if final {
				root.Content[i].LineComment = "#!final"
			}
			return
		}
	}
	key := yamlString(name)
	if final {
		key.LineComment = "#!final"
	}
	root.Content = append(root.Content, key, value)
}

func sortMirrorMapping(root *yaml.Node) {
	type entry struct{ key, value *yaml.Node }
	entries := make([]entry, 0, len(root.Content)/2)
	for i := 0; i < len(root.Content); i += 2 {
		entries = append(entries, entry{root.Content[i], root.Content[i+1]})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].key.Value < entries[j].key.Value })
	root.Content = nil
	for _, item := range entries {
		root.Content = append(root.Content, item.key, item.value)
	}
}

// PresetMirrorYAML preserves the complete current mirror context when CONDARC
// is replaced with the generated overlay. In particular, a private named
// channel must retain its private mapping instead of falling back to the
// public channel alias after its original nonstandard condarc is shadowed.
func PresetMirrorYAML(c Config) ([]byte, error) {
	root := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	context := c.PresetContext
	if context == "" && c.Defaults.CondaCaptured {
		context = c.Defaults.CondaYAML
	}
	if context != "" {
		var err error
		root, err = parseDefaultYAML(context)
		if err != nil {
			return nil, err
		}
	}
	defaults, known := mirrorChannels(c.CondaMirror)
	setMirrorMapping(root, "default_channels", yamlStrings(defaults), true)
	custom := mirrorMapping(root, "custom_channels")
	if custom == nil {
		custom = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	}
	for _, name := range []string{"conda-forge", "bioconda"} {
		setMirrorMapping(custom, name, yamlString(known[name]), false)
	}
	sortMirrorMapping(custom)
	setMirrorMapping(root, "custom_channels", custom, true)
	multi := mirrorMapping(root, "custom_multichannels")
	if multi == nil {
		multi = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	}
	setMirrorMapping(multi, "defaults", yamlStrings(defaults), true)
	sortMirrorMapping(multi)
	setMirrorMapping(root, "custom_multichannels", multi, true)
	if c.PresetChannelsSet || len(c.PresetChannels) != 0 || c.Defaults.CondaCaptured || context != "" {
		setMirrorMapping(root, "channels", yamlStrings(DesiredChannels(c)), true)
	}
	text, err := encodeMirrorYAML(root, "# Generated by Nido. Conda still merges other configuration sources.\n# Public presets replace supported channels; other private mappings are retained.\n")
	if err != nil {
		return nil, err
	}
	return []byte(text), nil
}
